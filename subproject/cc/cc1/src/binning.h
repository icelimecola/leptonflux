//========func
double GetEtilde(double x1, double x2, double gamma){
	if( gamma == 0 )
		return 0.5*(x1 + x2);
	else  if( gamma!=-1 )
		return pow( (pow(x2, gamma+1) - pow(x1, gamma+1))/(x2 - x1)/(1 + gamma), 1/gamma );
	else
		return exp( (log(x2) - log(x1))/(x2 - x1) );
}

int GetBinIndex(double x){
	if( x < energy_bins[0] || x >= energy_bins[nbin] ) return -1;
	for(int i=0; i<nbin; i++){
		if( x >= energy_bins[i] && x < energy_bins[i+1] ) return i;
	}
	return 0;
}

